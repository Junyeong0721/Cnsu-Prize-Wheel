import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import sharp from "sharp";
import pngToIco from "png-to-ico";

await mkdir("dist", { recursive: true });
await mkdir("build-resources", { recursive: true });
const logo = `data:image/png;base64,${(await readFile("assets/cnsu-logo.png")).toString("base64")}`;
await writeFile(
  "src/generated-assets.ts",
  `// Generated by npm run build.\nexport const LOGO = ${JSON.stringify(logo)};\n`,
);
const result = await build({
  entryPoints: ["src/main.tsx"],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: ["chrome120", "firefox120", "safari17"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "inline",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = await readFile("src/styles.css", "utf8");
const hash = createHash("sha256").update(js).digest("base64");
const csp = `default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; img-src data:; media-src data: blob:; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'`;
const html = `<!doctype html>\n<html lang="ko"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="${csp}"><meta name="description" content="충남도립대학교 홍보 행사용 돌림판. 설치와 로그인 없이 오프라인으로 사용하세요."><title>충남도립대학교 · CNSU 럭키 스핀</title><link rel="icon" href="${logo}"><style>${css}</style></head><body><div id="root"></div><noscript>돌림판 실행을 위해 브라우저의 JavaScript를 켜 주세요.</noscript><script>${js}</script></body></html>`;
await writeFile("dist/index.html", html);
await writeFile("dist/CNSU-Lucky-Spin.html", html);
const colors = [
  "#2856ab",
  "#00a6a1",
  "#82ba36",
  "#ffb32c",
  "#ec5c65",
  "#8f54a7",
];
const slices = colors
  .map((color, i) => {
    const a = (i * Math.PI) / 3 - Math.PI / 2,
      b = ((i + 1) * Math.PI) / 3 - Math.PI / 2;
    return `<path d="M128 128 L${128 + 104 * Math.cos(a)} ${128 + 104 * Math.sin(a)} A104 104 0 0 1 ${128 + 104 * Math.cos(b)} ${128 + 104 * Math.sin(b)} Z" fill="${color}" stroke="white" stroke-width="4"/>`;
  })
  .join("");
const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" rx="52" fill="#10285c"/><g>${slices}</g><circle cx="128" cy="128" r="32" fill="white"/><circle cx="128" cy="128" r="15" fill="#10285c"/><path d="M113 9h30l-15 36z" fill="white"/></svg>`;
const png = await sharp(Buffer.from(icon)).png().toBuffer();
await writeFile("build-resources/icon.png", png);
await writeFile("build-resources/icon.ico", await pngToIco(png));
console.log(
  `Built offline HTML (${Math.round(Buffer.byteLength(html) / 1024)} KB). All scripts, styles and images are embedded.`,
);
